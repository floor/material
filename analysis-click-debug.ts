import { chromium } from "playwright";
import * as sass from "sass";
import { resolve } from "node:path";
const prelude = '@use "abstract/emit" as arms-config with ($direction-arms: true);\n';
const sheet = sass.compileString(prelude + (await Bun.file("src/styles/main.scss").text()), { loadPaths: ["src/styles"], style: "compressed", logger: sass.Logger.silent }).css;
await Bun.write("analysis-entry.ts", `import createSlider from "${resolve("src/components/slider/index.ts")}";\n(window as any).createSlider = createSlider;\n`);
const bundle = await Bun.build({ entrypoints: [resolve("analysis-entry.ts")], target: "browser", format: "esm", minify: true });
const js = (await bundle.outputs[0]!.text()).replaceAll("\u0000", "\\u0000");
const server = Bun.serve({ hostname: "127.0.0.1", port: 0, fetch(req) {
  const p = new URL(req.url).pathname;
  if (p === "/slider.js") return new Response(js, { headers: { "Content-Type": "text/javascript" } });
  if (p === "/styles.css") return new Response(sheet, { headers: { "Content-Type": "text/css" } });
  return new Response(`<!doctype html><html data-theme="baseline" data-theme-mode="light"><head><link rel="stylesheet" href="/styles.css"><style>body{margin:0;padding:24px;background:#fff}#host{width:420px}</style></head><body><div id="host"></div><script type="module">import "/slider.js";window.ready=true;</script></body></html>`, { headers: { "Content-Type": "text/html" } });
}});
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 600, height: 300 } });
page.on("pageerror", (e) => console.log("PAGEERROR", e.message));
page.on("console", (m) => { if (m.type() === "warning" || m.type() === "error") console.log("CONSOLE", m.text().slice(0, 160)); });
await page.goto(`http://127.0.0.1:${server.port}`);
await page.waitForFunction(() => (window as any).ready);
await page.evaluate(() => { const s = (window as any).createSlider({ value: 80, size: "XL", label: "Volume" }); document.querySelector("#host")!.append(s.element); });
await page.waitForTimeout(300);
const box = await page.evaluate(() => { const c = document.querySelector(".mtrl-slider__container")!.getBoundingClientRect(); return { x: c.x + c.width * 0.33, y: c.y + c.height / 2 }; });
await page.evaluate(() => {
  const w = window as any;
  w.__f = [];
  const sample = () => {
    const el = document.querySelector(".mtrl-slider")!;
    const track = el.querySelector(".mtrl-slider__track")!.getBoundingClientRect();
    const handle = el.querySelector('[role="slider"]')!.getBoundingClientRect();
    const segs = [...el.querySelectorAll(".mtrl-slider__segment")].slice(1).map((s) => s.getBoundingClientRect());
    w.__f.push([+(handle.x + handle.width / 2 - track.left).toFixed(1), +(segs[0].right - track.left).toFixed(1), +(segs[1].left - track.left).toFixed(1), el.className.slice(0, 40)]);
    if (w.__f.length < 90) requestAnimationFrame(sample);
  };
  requestAnimationFrame(sample);
});
await page.mouse.move(box.x, box.y);
await page.mouse.down();
await page.waitForTimeout(60);
await page.mouse.up();
await page.waitForTimeout(900);
const f = await page.evaluate(() => (window as any).__f);
console.log(JSON.stringify(f.slice(0, 6)), "…", JSON.stringify(f.slice(-4)));
await browser.close(); server.stop(true);
