import { menuLoader, brokerMenu } from './broker.js';
const prefix = new URLSearchParams(location.search).get('prefix') ?? 'm';
const anchor = document.querySelector('#opener');
const host = document.querySelector(`${prefix}-menu`) ?? document.createElement(`${prefix}-menu`);
const shadowBefore = host.shadowRoot;
host.setAttribute('anchor', 'opener');
host.anchor = anchor;
host.setAttribute('aria-label', 'Actions');
if (!host.children.length) host.innerHTML = `<${prefix}-menu-item value="one">One</${prefix}-menu-item><${prefix}-menu-item value="last">Last</${prefix}-menu-item>`;
document.body.append(host);
const events = [];
const errors = [];
host.addEventListener('open', () => events.push('open'));
host.addEventListener('close', () => events.push('close'));
host.addEventListener('select', event => events.push(event.detail.value));
if (new URLSearchParams(location.search).has("initial")) host.open = true;
const load = menuLoader(prefix);
const detach = brokerMenu(anchor, host, load, error => errors.push(String(error)));
window.lab = { host, events, errors, load, detach, prefix, shadowBefore };
document.body.dataset.ready = 'true';
