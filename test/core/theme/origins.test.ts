// test/core/theme/origins.test.ts
//
// FLO-driven origin metadata on material/core/theme: the public THEME_ORIGINS
// map describes every built-in theme's standard palette. This holds the map to
// its sources — the generator's THEMES list, the generated headers of the
// .scss files, and the authored sources' own seed comments — pins the record
// shape (lowercase #rrggbb, contrast as generated, authored nulls), and proves
// the exhaustive partition of the theme directory. On main this file cannot
// import what it imports: the structured metadata is the contract.
import { describe, test, expect } from "bun:test";
import { readdirSync, readFileSync } from "node:fs";
import * as core from "../../../src/core";
import * as root from "../../../src";
import {
  AUTHORED_ORIGIN_SEEDS,
  THEMES,
  authoredSeedComments,
  renderCoreThemeIndex,
  themeOriginNames,
} from "../../../scripts/generate-themes";
import {
  BASELINE_SEED,
  THEME_ORIGINS,
  type BuiltInThemeName,
  type ThemeOrigin,
  type ThemeOriginVariant,
} from "../../../src/core/theme";

const THEMES_DIR = "src/styles/themes";
const THEME_FILES = readdirSync(THEMES_DIR)
  .filter((file) => /^_[a-z-]+\.scss$/.test(file) && !["_index.scss", "_base-theme.scss"].includes(file))
  .map((file) => file.slice(1, -5));

const records = THEME_ORIGINS as Readonly<Record<BuiltInThemeName, ThemeOrigin>>;
const names = Object.keys(records);
const isHex6 = (value: unknown): value is string => typeof value === "string" && /^#[0-9a-f]{6}$/.test(value);

/** The fields a generated theme's own .scss header records about its origin. */
const generatedHeader = (name: string): { seed: string; variant: string; secondary?: string; tertiary?: string; contrast: number } => {
  const header = readFileSync(`${THEMES_DIR}/_${name}.scss`, "utf8").match(/^\/\/ Generated by scripts\/generate-themes\.ts \((.+)\) with$/m);
  expect(header, `${name}: no generated-origin header`).toBeTruthy();
  const fields = header![1]!;
  const seed = fields.match(/\bseed (#[0-9a-fA-F]{6})/)?.[1];
  const variant = fields.match(/\bvariant ([A-Za-z][A-Za-z ]*?)(?:[,)]|$)/)?.[1];
  expect(seed, `${name}: header has no seed`).toBeTruthy();
  expect(variant, `${name}: header has no variant`).toBeTruthy();
  return {
    seed: seed!.toLowerCase(),
    variant: variant!.toLowerCase().replace(/\s+/g, "-"),
    secondary: fields.match(/\bsecondary (#[0-9a-fA-F]{6})/)?.[1]?.toLowerCase(),
    tertiary: fields.match(/\btertiary (#[0-9a-fA-F]{6})/)?.[1]?.toLowerCase(),
    contrast: Number(fields.match(/\bcontrastLevel ([\d.]+)/)?.[1] ?? 0),
  };
};

describe("theme origin metadata", () => {
  test("the emitted region is what the generator emits", () => {
    expect(readFileSync("src/core/theme/index.ts", "utf8")).toBe(renderCoreThemeIndex());
  });

  test("every generated record matches its THEMES spec and its generated header", () => {
    for (const spec of THEMES) {
      const record = records[spec.name as BuiltInThemeName];
      expect(record, `${spec.name} has a record`).toBeDefined();
      if (record?.kind !== "generated") {
        expect(record, `${spec.name} is generated`).toMatchObject({ kind: "generated" });
        continue;
      }
      expect(record.seed).toBe(spec.seed.toLowerCase());
      expect(record.variant).toBe(spec.variant);
      expect(record.contrast).toBe(spec.contrast ?? 0);
      expect(record.secondary ?? null).toBe(spec.secondary?.toLowerCase() ?? null);
      expect(record.tertiary ?? null).toBe(spec.tertiary?.toLowerCase() ?? null);
      const header = generatedHeader(spec.name);
      expect(record.seed).toBe(header.seed);
      expect(record.variant).toBe(header.variant as ThemeOriginVariant);
      expect(record.secondary ?? null).toBe(header.secondary ?? null);
      expect(record.contrast).toBe(header.contrast);
    }
    expect(THEMES.filter((spec) => records[spec.name as BuiltInThemeName]?.kind === "generated")).toHaveLength(THEMES.length);
  });

  test("the two-colour seeds and the high-contrast input are carried, not normalized away", () => {
    const secondary: Record<string, string> = {};
    for (const name of names) {
      const record = records[name as BuiltInThemeName];
      if (record?.kind === "generated" && record.secondary !== undefined) {
        expect(isHex6(record.secondary), `${name}: secondary ${record.secondary}`).toBe(true);
        secondary[name] = record.secondary;
      }
    }
    expect(Object.keys(secondary).sort()).toEqual(["brownbeige", "desert", "sageivory", "summer", "tealcaramel"]);
    expect(secondary.desert).toBe("#4a87c4");
    expect(records.highcontrast).toMatchObject({ kind: "generated", contrast: 1, variant: "tonal-spot" });
  });

  test("records are lowercase #rrggbb, baseline is the documented seed, contrast is a number", () => {
    expect(BASELINE_SEED).toBe("#6750a4");
    expect(records.baseline).toMatchObject({ kind: "baseline", seed: "#6750a4", variant: "tonal-spot", contrast: 0 });
    for (const name of names) {
      const record = records[name as BuiltInThemeName];
      if (record?.kind === "generated") {
        expect(isHex6(record.seed), `${name}: seed ${record.seed}`).toBe(true);
        expect(typeof record.contrast).toBe("number");
        expect(record.contrast).toBe(Math.trunc(record.contrast));
      }
    }
  });

  test("the authored seeds are exactly the documented source comments; autumn stays null", () => {
    const { authored } = themeOriginNames();
    expect(authored.sort()).toEqual(["autumn", "forest", "ocean", "spring", "sunset"]);
    for (const name of authored) {
      const record = records[name as BuiltInThemeName];
      expect(record, `${name} has a record`).toBeDefined();
      if (record?.kind !== "authored") {
        expect(record, `${name} is authored`).toMatchObject({ kind: "authored" });
        continue;
      }
      expect(record).toMatchObject({ variant: null, contrast: null });
      expect(AUTHORED_ORIGIN_SEEDS[name]).toBe(authoredSeedComments(name));
      expect(record.seed).toBe(authoredSeedComments(name));
      if (record.seed !== null) expect(isHex6(record.seed), `${name}: seed ${record.seed}`).toBe(true);
    }
    // No fallback to a computed primary: autumn's source records brown as
    // primary, its contrast header carries that as a seed, and the record
    // still says null.
    expect(records.autumn).toMatchObject({ kind: "authored", seed: null });
    const autumnPrimary = readFileSync(`${THEMES_DIR}/_autumn.scss`, "utf8")
      .match(/--#\{\$prefix\}-sys-color-primary:\s*(#[0-9a-fA-F]{6})/)?.[1]?.toLowerCase();
    expect(autumnPrimary).toBe("#795548");
    expect((records.autumn as { seed: string | null }).seed).not.toBe(autumnPrimary);
  });

  test("the map partitions every theme file, with no overlap and no unclassified theme", () => {
    const { baseline, generated, authored } = themeOriginNames();
    expect([...names].sort()).toEqual([...THEME_FILES].sort());
    const classes: string[][] = [[baseline], generated, authored];
    expect(new Set(classes.flat()).size).toBe(baseline ? generated.length + authored.length + 1 : 0);
    for (const [kind, members] of [["baseline", [baseline]], ["generated", generated], ["authored", authored]] as const) {
      for (const name of members) {
        expect(records[name as BuiltInThemeName]?.kind, `${name} classifies as ${kind}`).toBe(kind);
      }
    }
  });

  test("the map is frozen and cannot be edited", () => {
    expect(Object.isFrozen(THEME_ORIGINS)).toBe(true);
    for (const name of names) expect(Object.isFrozen(records[name as BuiltInThemeName])).toBe(true);
    expect(() => { (records.desert as { seed?: string }).seed = "#000000"; }).toThrow(TypeError);
    expect((records.desert as { seed: string }).seed).toBe("#9a7a3e");
    expect(() => { (THEME_ORIGINS as Record<string, unknown>).extra = 1; }).toThrow(TypeError);
    expect("extra" in THEME_ORIGINS).toBe(false);
  });

  test("the root and material/core keep their explicit re-exports", () => {
    expect((core as Record<string, unknown>).THEME_ORIGINS).toBeUndefined();
    expect((core as Record<string, unknown>).BASELINE_SEED).toBeUndefined();
    expect((root as Record<string, unknown>).THEME_ORIGINS).toBeUndefined();
    expect((root as Record<string, unknown>).BASELINE_SEED).toBeUndefined();
  });
});
